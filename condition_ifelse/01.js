// Write a JavaScript program that checks if a number is positive, negative, or zero. Print "Positive" if the number is positive, "Negative" if the number is negative, and "Zero" if the number is zero.

let num = Number(prompt("Enter a number"));

if (num > 0) {
    console.log("The number is positive");
} else if (num < 0) {
    console.log("The number is negative");
} else {
    console.log("The number is zero");
}
